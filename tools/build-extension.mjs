// Assemble the browser extension (extension/) from the shared web code:
//   node tools/build-extension.mjs        (after wasm-pack has built web/pkg)
// Then load extension/ in chrome://extensions ("Load unpacked").
//
// Copies web/lib (loader, tokenizer, agent), web/vendor and the wasm build, wraps lib/dom-agent.js
// as a plain script for chrome.scripting, and draws the icons.
import { copyFileSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { deflateSync } from "node:zlib";

const root = resolve(import.meta.dirname, "..");
const ext = join(root, "extension");
const copy = (from, to) => {
  mkdirSync(join(ext, to, ".."), { recursive: true });
  copyFileSync(join(root, from), join(ext, to));
};

for (const f of ["webyiq.js", "tokenizer.js", "agent-core.js", "dom-agent.js", "site.css"]) copy(`web/lib/${f}`, `lib/${f}`);
for (const f of readdirSync(join(root, "web/vendor"))) copy(`web/vendor/${f}`, `vendor/${f}`);
for (const f of ["webyiq_web.js", "webyiq_web_bg.wasm"]) copy(`web/pkg/${f}`, `pkg/${f}`);

// dom-agent.js as a script that can be injected repeatedly: no exports, own scope, one global
const dom = readFileSync(join(root, "web/lib/dom-agent.js"), "utf8").replace(/^export /gm, "");
writeFileSync(join(ext, "lib/dom-agent.classic.js"),
  `// Generated by tools/build-extension.mjs from web/lib/dom-agent.js.\n(() => {\n${dom}\nglobalThis.__webyiqDom = { observePage, actOnPage };\n})();\n`);

// icons: the logo's gradient squircle with a white ring, 4x4 supersampled
function png(size) {
  const lerp = (a, b, t) => a + (b - a) * t;
  const stops = [[0, [0x8b, 0x6c, 0xff]], [0.45, [0x5b, 0x8c, 0xff]], [1, [0x22, 0xd3, 0xee]]];
  const grad = (t) => {
    const i = t < stops[1][0] ? 0 : 1;
    const [t0, c0] = stops[i], [t1, c1] = stops[i + 1];
    const u = (t - t0) / (t1 - t0);
    return c0.map((c, k) => lerp(c, c1[k], u));
  };
  const rows = [];
  const r = size * 0.24, ss = 4;
  for (let y = 0; y < size; y++) {
    const row = [0];
    for (let x = 0; x < size; x++) {
      let a = 0, w = 0;
      for (let sy = 0; sy < ss; sy++) for (let sx = 0; sx < ss; sx++) {
        const px = x + (sx + 0.5) / ss, py = y + (sy + 0.5) / ss;
        const dx = Math.max(r - px, 0, px - (size - r)), dy = Math.max(r - py, 0, py - (size - r));
        if (dx * dx + dy * dy > r * r) continue;
        a++;
        const d = Math.hypot(px - size / 2, py - size / 2) / size;
        if (Math.abs(d - 0.2) < 0.055) w++;
      }
      const [cr, cg, cb] = grad((x + y) / (2 * size));
      const wf = a ? w / a : 0;
      row.push(...[cr, cg, cb].map((c) => Math.round(lerp(c, 255, wf))), Math.round((a / (ss * ss)) * 255));
    }
    rows.push(Buffer.from(row));
  }
  const crcTable = Array.from({ length: 256 }, (_, n) => {
    let c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    return c >>> 0;
  });
  const crc = (buf) => {
    let c = 0xffffffff;
    for (const b of buf) c = crcTable[(c ^ b) & 0xff] ^ (c >>> 8);
    return (c ^ 0xffffffff) >>> 0;
  };
  const chunk = (type, data) => {
    const len = Buffer.alloc(4);
    len.writeUInt32BE(data.length);
    const body = Buffer.concat([Buffer.from(type), data]);
    const c = Buffer.alloc(4);
    c.writeUInt32BE(crc(body));
    return Buffer.concat([len, body, c]);
  };
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(size, 0);
  ihdr.writeUInt32BE(size, 4);
  ihdr.set([8, 6, 0, 0, 0], 8); // 8-bit RGBA
  return Buffer.concat([Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]), chunk("IHDR", ihdr),
    chunk("IDAT", deflateSync(Buffer.concat(rows))), chunk("IEND", Buffer.alloc(0))]);
}
mkdirSync(join(ext, "icons"), { recursive: true });
for (const s of [16, 32, 48, 128]) writeFileSync(join(ext, `icons/icon${s}.png`), png(s));

console.log(`extension assembled in ${ext}`);
